/** Small, local transcript formatter. HTML input is never copied from the chat site. */
(function (root, factory) {
  if (typeof module === "object" && module.exports) module.exports = factory();
  else root.SafeShareTranscript = factory();
})(typeof globalThis !== "undefined" ? globalThis : this, function () {
  // ponytail: arithmetic LaTeX becomes readable text, not a full TeX renderer.
  function math(text) {
    return text.replace(/\\(?:,|;|!|quad\b|qquad\b)/g, " ")
      .replace(/\\(?:times|cdot)\b/g, " × ").replace(/\\div\b/g, " ÷ ")
      .replace(/\\%/g, "%").replace(/\\(?:text|mathrm)\{([^{}]*)\}/g, "$1")
      .replace(/\\(?:left|right)\b/g, "").replace(/[ \t]+/g, " ").trim();
  }
  function normalize(text) {
    return text.split(/(```[\s\S]*?(?:```|$)|`[^`\n]*`)/g).map(part => part.startsWith("`") ? part :
      part.replace(/\\{1,2}\[([\s\S]*?)\\{1,2}\]|\\\(([\s\S]*?)\\\)/g, (_, block, inline) => math(block ?? inline)))
      .join("");
  }
  function extract(node) {
    if (node.nodeType === 3) return node.textContent;
    if (node.nodeType !== 1) return "";
    if (node.matches("script, style, button, annotation, .katex-html")) return "";
    if (node.matches(".katex")) {
      const tex = node.querySelector('annotation[encoding="application/x-tex"]');
      if (tex) return math(tex.textContent);
    }
    if (node.matches("pre")) return "\n\n```\n" + node.textContent + "\n```\n\n";
    if (node.matches("table")) {
      const rows = [...node.rows].map(row => [...row.cells].map(cell =>
        [...cell.childNodes].map(extract).join("").trim().replace(/\|/g, "\\|").replace(/\s*\n\s*/g, " ")));
      return "\n\n" + rows.map((row, i) => "| " + row.join(" | ") + " |" +
        (i === 0 ? "\n| " + row.map(() => "---").join(" | ") + " |" : "")).join("\n") + "\n\n";
    }
    const text = [...node.childNodes].map(extract).join("");
    if (/^H[1-6]$/.test(node.tagName)) return "\n\n" + "#".repeat(+node.tagName[1]) + " " + text.trim() + "\n\n";
    if (node.tagName === "BR") return "\n";
    if (node.tagName === "LI") return "\n- " + text.trim() + "\n";
    if (["P", "DIV", "SECTION", "UL", "OL"].includes(node.tagName)) return "\n" + text + "\n";
    return text;
  }
  // Accept ONLY escaped content plus badges generated by the modal, never raw chat HTML.
  function renderEscaped(html) {
    const lines = html.split("\n");
    const output = [];
    let code = false;
    // Preview only: like the shared viewer, a run of blank lines is one paragraph break and
    // blank lines at the start or end of a message are dropped. Code blocks keep every line.
    let started = false, gap = false;
    for (let i = 0; i < lines.length; i++) {
      const line = lines[i];
      if (!code && /^[\s\u00a0\u200b-\u200d\u2060\ufeff]*$/.test(line)) { gap = started; continue; }
      if (gap) { output.push("<br>"); gap = false; }
      started = true;
      if (/^\s*```/.test(line)) { output.push(code ? "</code></pre>" : "<pre><code>"); code = !code; continue; }
      if (code) { output.push(line + "\n"); continue; }
      if (/^\s*\|.*\|\s*$/.test(line) && /^\s*\|[\s:|\-]+\|\s*$/.test(lines[i + 1] || "")) {
        const cells = row => row.trim().slice(1, -1).split(/(?<!\\)\|/).map(c => c.trim().replace(/\\\|/g, "|"));
        output.push('<div class="ss-table-wrap"><table><thead><tr>' + cells(line).map(c => `<th>${c}</th>`).join("") + "</tr></thead><tbody>");
        i++;
        while (/^\s*\|.*\|\s*$/.test(lines[i + 1] || "")) {
          output.push("<tr>" + cells(lines[++i]).map(c => `<td>${c}</td>`).join("") + "</tr>");
        }
        output.push("</tbody></table></div>");
      } else {
        const heading = /^(#{1,6})\s+(.+)$/.exec(line);
        output.push(heading ? `<h${heading[1].length}>${heading[2]}</h${heading[1].length}>` : line + "<br>");
      }
    }
    if (code) output.push("</code></pre>");
    return output.join("");
  }
  return { math, normalize, extract, renderEscaped };
});
